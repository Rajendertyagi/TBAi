/**
 * A keyboard hint rendered at the trailing edge of a menu item.
 *
 * Deliberately NOT byte-identical to shadcn's `ContextMenuShortcut`, which
 * ships a bare `<span>`. The one change here is `aria-hidden`: a shortcut is a
 * visual affordance, and leaving it readable makes the item's accessible name
 * "Cut Ctrl+X" — which stops every consumer that addresses the item by name
 * from matching "Cut", including the `exact: true` locators in the e2e specs.
 *
 * The shortcut is still announced, via `aria-keyshortcuts` on the ITEM itself,
 * which is the mechanism MDN documents for exactly this. `textValue` is also
 * the caller's responsibility and cannot live here, because Radix derives
 * typeahead from the item's own `textContent` and this span is inside it — so
 * an item carrying a shortcut must pass `textValue` to keep typeahead on the
 * label.
 *
 * See "ADR: Context menus deviate from shadcn's ContextMenuShortcut, on
 * purpose" in `docs/decisions.md` before re-syncing this file from the shadcn
 * registry, which would undo this.
 */
function ContextMenuShortcut({
  className,
  ...props
}: React.HTMLAttributes<HTMLSpanElement>) {
  return (
    <span
      aria-hidden="true"
      data-slot="context-menu-shortcut"
      className={cn(
        "ml-auto text-xs font-normal tracking-wide text-muted-foreground/70",
        className,
      )}
      {...props}
    />
  );
}

