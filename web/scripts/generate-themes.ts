/**
 * Generates web/src/styles/themes.css and web/src/features/appearance/theme-data.ts
 * from all standard shadcn registry JSON files in web/src/themes/*.json.
 *
 * SINGLE SOURCE OF TRUTH for all theme token resolution.
 * Strictly enforces:
 * - App-owned Geometry Invariant (--radius: 0.625rem)
 * - Sleek Borderless / Hairline Surface Contract
 * - Guaranteed Status Bar & Link Text Legibility
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";
import { contrastRatio, mix, parseColor } from "../src/features/appearance/theme-color.ts";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const webRoot = path.resolve(__dirname, "..");
const themesDir = path.join(webRoot, "src", "themes");
const outCssPath = path.join(webRoot, "src", "styles", "themes.css");
const outDataPath = path.join(webRoot, "src", "features", "appearance", "theme-data.ts");

export interface ThemeJson {
  name?: string;
  type?: string;
  cssVars?: {
    theme?: Record<string, string>;
    light?: Record<string, string>;
    dark?: Record<string, string>;
  };
}

export interface ThemeSwatch {
  background: string;
  surface: string;
  primary: string;
}

export interface ThemeDefinition {
  id: string;
  name: string;
  builtin?: boolean;
  swatch: {
    light: ThemeSwatch;
    dark: ThemeSwatch;
  };
  tokens: {
    light: Record<string, string>;
    dark: Record<string, string>;
  };
}

function toTitleCase(slug: string): string {
  return slug
    .split(/[-_\s]+/)
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1).toLowerCase())
    .join(" ");
}

export function generateThemes() {
  if (!fs.existsSync(themesDir)) {
    console.error(`[themes] Directory not found: ${themesDir}`);
    return;
  }

  const files = fs
    .readdirSync(themesDir)
    .filter((f) => f.endsWith(".json"))
    .sort((a, b) => {
      // Put default.json first
      if (a.toLowerCase().startsWith("default")) return -1;
      if (b.toLowerCase().startsWith("default")) return 1;
      return a.localeCompare(b);
    });

  const themes: ThemeDefinition[] = [];
  const cssBlocks: string[] = [
    "/**",
    " * DO NOT EDIT DIRECTLY.",
    " * Auto-generated by web/scripts/generate-themes.ts from web/src/themes/*.json.",
    " *",
    ' * Specificity rule: html[data-tbai-theme="x"] outranks :root, and',
    ' * html[data-tbai-theme="x"].dark outranks .dark.',
    " * Built-in 'default' theme is omitted here; styled natively by globals.css.",
    " */",
    "",
  ];

  for (const file of files) {
    const filePath = path.join(themesDir, file);
    let raw: ThemeJson;
    try {
      raw = JSON.parse(fs.readFileSync(filePath, "utf-8")) as ThemeJson;
    } catch (err) {
      console.warn(`[themes] Skipping invalid JSON theme file: ${file}`, err);
      continue;
    }

    const slug = path.basename(file, ".json").toLowerCase();
    const displayName = raw.name ? toTitleCase(raw.name) : toTitleCase(slug);

    const lightRaw = { ...(raw.cssVars?.light || {}) };
    const darkRaw = { ...(raw.cssVars?.dark || {}) };

    // Resolve complete 33-token dictionary for both light and dark
    const lightTokens = resolveThemeVariables(slug, lightRaw, false);
    const darkTokens = resolveThemeVariables(slug, darkRaw, true);

    const isBuiltin = slug === "default";

    // Build Swatches from the exact resolved tokens
    const swatchLight: ThemeSwatch = {
      background: lightTokens["--background"],
      surface: lightTokens["--card"],
      primary: lightTokens["--primary"],
    };

    const swatchDark: ThemeSwatch = {
      background: darkTokens["--background"],
      surface: darkTokens["--card"],
      primary: darkTokens["--primary"],
    };

    themes.push({
      id: slug,
      name: displayName,
      builtin: isBuiltin,
      swatch: {
        light: swatchLight,
        dark: swatchDark,
      },
      tokens: {
        light: lightTokens,
        dark: darkTokens,
      },
    });

    // Generate CSS blocks (omit builtin 'default' so globals.css remains the single source of truth for default)
    if (!isBuiltin) {
      cssBlocks.push(renderCssBlock(slug, lightTokens, false));
      cssBlocks.push("");
      cssBlocks.push(renderCssBlock(slug, darkTokens, true));
      cssBlocks.push("");
    }
  }

  // Write themes.css
  fs.writeFileSync(outCssPath, cssBlocks.join("\n"), "utf-8");
  console.log(`[themes] Wrote ${themes.length - 1} non-builtin themes to ${outCssPath}`);

  // Write theme-data.ts
  const dataTsContent = [
    "/**",
    " * DO NOT EDIT DIRECTLY.",
    " * Auto-generated by web/scripts/generate-themes.ts from web/src/themes/*.json.",
    " */",
    "",
    'export type ThemeVariant = "light" | "dark";',
    "",
    "export interface ThemeSwatch {",
    "  background: string;",
    "  surface: string;",
    "  primary: string;",
    "}",
    "",
    "export interface ThemeDefinition {",
    "  id: string;",
    "  name: string;",
    "  builtin?: boolean;",
    "  swatch: {",
    "    light: ThemeSwatch;",
    "    dark: ThemeSwatch;",
    "  };",
    "  tokens: {",
    "    light: Record<string, string>;",
    "    dark: Record<string, string>;",
    "  };",
    "}",
    "",
    'export const DEFAULT_THEME_ID = "default";',
    "",
    `export const THEMES: readonly ThemeDefinition[] = ${JSON.stringify(themes, null, 2)} as const;`,
    "",
    "export function getTheme(id: string): ThemeDefinition | undefined {",
    "  return THEMES.find((t) => t.id === id);",
    "}",
    "",
    "export function isThemeId(id: unknown): id is string {",
    '  return typeof id === "string" && THEMES.some((t) => t.id === id);',
    "}",
    "",
  ].join("\n");

  fs.writeFileSync(outDataPath, dataTsContent, "utf-8");
  console.log(`[themes] Wrote theme registry with full token fidelity to ${outDataPath}`);

  // Keep generated output stable with the repository formatter.
  const format = spawnSync("bunx", ["biome", "format", "--write", outCssPath, outDataPath], {
    cwd: path.resolve(webRoot, ".."),
    stdio: "inherit",
  });
  if (format.status !== 0) {
    throw new Error(`[themes] biome format failed for generated theme files (exit ${format.status ?? "unknown"})`);
  }
}

export function resolveThemeVariables(
  slug: string,
  vars: Record<string, string>,
  isDark: boolean,
): Record<string, string> {
  const result: Record<string, string> = {};

  for (const [k, v] of Object.entries(vars)) {
    // FILTER: Typography and structural geometry are strictly app-owned
    if (
      k.startsWith("font-") ||
      k.startsWith("tracking-") ||
      k === "spacing" ||
      k === "radius" ||
      k.startsWith("shadow-")
    ) {
      continue;
    }
    const prop = k.startsWith("--") ? k : `--${k}`;
    result[prop] = v;
  }

  // 1. App-Owned Geometry Invariant:
  // Lock corner radius to TBAi's standard design (0.625rem / 10px).
  // Community JSONs cannot force 0px boxes or 1.5rem balloons on buttons and cards.
  result["--radius"] = "0.625rem";

  // Canonical TBAi Fallbacks
  const bg = vars.background || (isDark ? "oklch(0.145 0 0)" : "oklch(1 0 0)");
  const fg = vars.foreground || (isDark ? "oklch(0.985 0 0)" : "oklch(0.145 0 0)");
  const card = vars.card || bg;
  const cardFg = vars["card-foreground"] || fg;
  const popover = vars.popover || card;
  const popoverFg = vars["popover-foreground"] || cardFg;
  const primary = vars.primary || (isDark ? "oklch(0.87 0 0)" : "oklch(0.21 0 0)");
  const primaryFg = vars["primary-foreground"] || (isDark ? "oklch(0.2 0 0)" : "oklch(0.985 0 0)");
  const secondary = vars.secondary || vars.muted || (isDark ? "oklch(0.269 0 0)" : "oklch(0.967 0 0)");
  const secondaryFg = vars["secondary-foreground"] || (isDark ? "oklch(0.985 0 0)" : "oklch(0.21 0 0)");
  const muted = vars.muted || secondary;
  const mutedFg = vars["muted-foreground"] || (isDark ? "oklch(0.708 0 0)" : "oklch(0.552 0 0)");
  const accent = vars.accent || muted;
  const accentFg = vars["accent-foreground"] || fg;
  const destructive = vars.destructive || (isDark ? "oklch(0.702 0.19 22.2)" : "oklch(0.637 0.208 25.3)");
  const destructiveFg = vars["destructive-foreground"] || (isDark ? "oklch(0.985 0 0)" : "oklch(0.985 0 0)");

  // 2. Sleek Hairline Border Contract:
  // Community themes often set border to pitch black oklch(0 0 0), which creates harsh cut lines.
  // Normalize border to a sleek, refined hairline tint relative to foreground.
  const isHarshBorder =
    !vars.border ||
    vars.border === "oklch(0 0 0)" ||
    vars.border === "oklch(0.0000 0 0)" ||
    vars.border === "#000000" ||
    vars.border === "black";

  const border = isHarshBorder
    ? isDark
      ? "color-mix(in srgb, var(--foreground) 12%, transparent)"
      : "color-mix(in srgb, var(--foreground) 9%, transparent)"
    : vars.border;

  const isHarshSidebarBorder =
    !vars["sidebar-border"] ||
    vars["sidebar-border"] === "oklch(0 0 0)" ||
    vars["sidebar-border"] === "oklch(0.0000 0 0)" ||
    vars["sidebar-border"] === "#000000" ||
    vars["sidebar-border"] === "black";

  const sidebarBorder = isHarshSidebarBorder
    ? isDark
      ? "color-mix(in srgb, var(--sidebar-foreground) 10%, transparent)"
    : "color-mix(in srgb, var(--sidebar-foreground) 8%, transparent)"
    : vars["sidebar-border"] || border;

  const input = vars.input || border;
  const ring = vars.ring || primary;

  if (!result["--background"]) result["--background"] = bg;
  if (!result["--foreground"]) result["--foreground"] = fg;
  if (!result["--card"]) result["--card"] = card;
  if (!result["--card-foreground"]) result["--card-foreground"] = cardFg;
  if (!result["--popover"]) result["--popover"] = popover;
  if (!result["--popover-foreground"]) result["--popover-foreground"] = popoverFg;
  if (!result["--primary"]) result["--primary"] = primary;
  if (!result["--primary-foreground"]) result["--primary-foreground"] = primaryFg;
  if (!result["--secondary"]) result["--secondary"] = secondary;
  if (!result["--secondary-foreground"]) result["--secondary-foreground"] = secondaryFg;
  if (!result["--muted"]) result["--muted"] = muted;
  if (!result["--muted-foreground"]) result["--muted-foreground"] = mutedFg;
  if (!result["--accent"]) result["--accent"] = accent;
  if (!result["--accent-foreground"]) result["--accent-foreground"] = accentFg;
  if (!result["--destructive"]) result["--destructive"] = destructive;
  if (!result["--destructive-foreground"]) result["--destructive-foreground"] = destructiveFg;
  result["--border"] = border;
  if (!result["--input"]) result["--input"] = input;
  if (!result["--ring"]) result["--ring"] = ring;

  if (!result["--sidebar"]) result["--sidebar"] = card;
  if (!result["--sidebar-foreground"]) result["--sidebar-foreground"] = cardFg;
  if (!result["--sidebar-primary"]) result["--sidebar-primary"] = primary;
  if (!result["--sidebar-primary-foreground"]) result["--sidebar-primary-foreground"] = primaryFg;
  if (!result["--sidebar-accent"]) result["--sidebar-accent"] = accent;
  if (!result["--sidebar-accent-foreground"]) result["--sidebar-accent-foreground"] = accentFg;
  result["--sidebar-border"] = sidebarBorder;
  if (!result["--sidebar-ring"]) result["--sidebar-ring"] = ring;

  // 3. Status Bar & Link Text Contrast Contract:
  // In StatusBar.tsx, text is text-muted-foreground.
  // We offset statusbar subtly from background so text is 100% readable in every theme.
  const ensureContrast = (candidate: string, against: string, toward: string, min = 4.5): string => {
    const bgc = parseColor(against);
    let current = candidate;
    if (!bgc) return current;
    for (let i = 0; i <= 20; i++) {
      const fgc = parseColor(current);
      if (fgc && contrastRatio(fgc, bgc) >= min) return current;
      current = mix(current, toward, 0.12);
    }
    return toward;
  };

  // Ensure muted-foreground is readable on background and statusbar (status bar uses it).
  result["--muted-foreground"] = ensureContrast(result["--muted-foreground"] || mutedFg, bg, fg);

  const statusbarBase = isDark ? mix(bg, fg, 0.1) : mix(bg, fg, 0.06);
  // Ensure muted-foreground remains readable on statusbar.
  {
    let sb = statusbarBase;
    const mfg = parseColor(result["--muted-foreground"]);
    for (let i = 0; i < 40; i++) {
      const sbc = parseColor(sb);
      if (mfg && sbc && contrastRatio(mfg, sbc) >= 4.5) break;
      const towardBg = mix(sb, bg, 0.2);
      const towardFg = mix(sb, fg, 0.2);
      const rBg = mfg && parseColor(towardBg) ? contrastRatio(mfg, parseColor(towardBg)!) : 0;
      const rFg = mfg && parseColor(towardFg) ? contrastRatio(mfg, parseColor(towardFg)!) : 0;
      const next = rFg > rBg ? towardFg : towardBg;
      if (next === sb) break;
      sb = next;
    }
    // If still insufficient, fall back to background and strengthen muted-foreground.
    let mfgc = parseColor(result["--muted-foreground"]);
    let sbc = parseColor(sb);
    if (mfgc && sbc && contrastRatio(mfgc, sbc) < 4.5) {
      sb = bg;
      result["--muted-foreground"] = ensureContrast(result["--muted-foreground"], sb, fg);
    }
    result["--statusbar"] = sb;
  }

  // Links in prose must maintain high contrast as text (not button fills).
  const linkBase = isDark
    ? "oklch(0.8711 0.0055 286.3)"
    : vars.primary || "oklch(0.2103 0.0059 285.9)";
  result["--link"] = ensureContrast(linkBase, bg, fg);
  const linkHoverBase = isDark ? "oklch(0.95 0 0)" : vars.foreground || "oklch(0.1408 0.0044 285.8)";
  result["--link-hover"] = ensureContrast(linkHoverBase, bg, fg);

  if (!result["--success"]) {
    result["--success"] = isDark ? "oklch(0.8003 0.1821 151.7)" : "oklch(0.6271 0.1699 149.2)";
  }
  if (!result["--success-foreground"]) {
    result["--success-foreground"] = isDark ? "oklch(0.1448 0 0)" : "oklch(0.9851 0 0)";
  }
  if (!result["--warning"]) {
    result["--warning"] = isDark ? "oklch(0.8369 0.1644 84.4)" : "oklch(0.6658 0.1574 58.3)";
  }
  if (!result["--warning-foreground"]) {
    result["--warning-foreground"] = isDark ? "oklch(0.1448 0 0)" : "oklch(0.9851 0 0)";
  }

  // 4. Borderless Soft Card & Ring Surface Contract (Linear / Vercel modern standard):
  result["--card-soft"] = `color-mix(in srgb, var(--foreground) ${isDark ? "4%" : "2.5%"}, transparent)`;
  result["--card-outline"] = `color-mix(in srgb, var(--foreground) 6%, transparent)`;

  return result;
}

function renderCssBlock(slug: string, tokens: Record<string, string>, isDark: boolean): string {
  const selector = isDark
    ? `html[data-tbai-theme="${slug}"].dark`
    : `html[data-tbai-theme="${slug}"]:not(.dark)`;

  const lines = [`${selector} {`];

  for (const [prop, val] of Object.entries(tokens)) {
    lines.push(`  ${prop}: ${val};`);
  }

  lines.push("}");
  return lines.join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  generateThemes();
}
