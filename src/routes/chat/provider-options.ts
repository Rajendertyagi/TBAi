import type { ProviderConfig } from "../../types";

/**
 * The AI SDK's provider-options contract, restated locally.
 *
 * The SDK types `providerOptions` as `Record<string, JSONObject>`, but that
 * alias lives in `@ai-sdk/provider` — a transitive package this repo does not
 * declare, and AGENTS.md forbids depending on undeclared transitives. Mirroring
 * the shape keeps the boundary explicit and still rejects non-JSON values.
 */
type JsonValue = string | number | boolean | null | JsonValue[] | JsonObject;
type JsonObject = { [key: string]: JsonValue };

/** Options keyed by provider, as `streamText` accepts them. */
export type ReasoningProviderOptions = Record<string, JsonObject>;

/**
 * Build provider-specific options for reasoning display.
 *
 * AI SDK v7 handles reasoning effort mapping portably across OpenAI, Anthropic,
 * Google, and OpenAI-compatible providers via streamText's top-level `reasoning`
 * option.
 *
 * Google is the exception: while AI SDK maps `reasoning` to `thinkingBudget` or
 * `thinkingLevel`, Google suppresses thought summaries in the API response
 * unless `includeThoughts: true` is explicitly requested in `thinkingConfig`.
 * We set only `includeThoughts: true` without overwriting the budget/level
 * fields generated by the SDK.
 *
 * @param provider - The provider configuration.
 * @param reasoning - The effective level: `"low"`, `"medium"`, `"high"` or `"off"`.
 * @returns The provider-specific options bag (only `{ google: { thinkingConfig: { includeThoughts: true } } }` when Google reasoning is active).
 */
export function buildReasoningProviderOptions(
  provider: Pick<ProviderConfig, "type">,
  reasoning: string,
): ReasoningProviderOptions {
  if (reasoning === "off") return {};

  if (provider.type === "google") {
    return {
      google: {
        thinkingConfig: {
          includeThoughts: true,
        },
      },
    };
  }

  return {};
}
